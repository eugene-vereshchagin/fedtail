"""One file with everything inside — fedtail for people without Python.

    python3 packaging/build.py            # → dist/fedtail (Linux) or dist/fedtail.exe

PyInstaller packs Python, Qt (PySide6) and fedtail into a single executable that
unpacks itself on start. The version, commit and date of the build are written
into fedtail/_build.py first (there is no git inside the file), and removed after.
Running from the source with Python stays as it was: `python3 -m fedtail`.
"""

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WINDOWS = sys.platform == "win32"

# Libraries the Linux build takes from the system it runs on, not from the one it was
# built on: fontconfig and freetype must match the system's font configuration (an
# older fontconfig can't read a newer /etc/fonts — every font falls apart), the
# keyboard and D-Bus libraries their system services. Every Linux desktop has them.
SYSTEM_LIBS = ("libfontconfig", "libfreetype", "libxkbcommon", "libdbus-1")

SPEC = """# generated by packaging/build.py
import os
from PyInstaller.utils.hooks import collect_submodules

# Qt's platform plugins, all of them: without the Wayland ones a Wayland desktop
# (Plasma 6) runs us through XWayland — unscaled, tiny letters, a window sized wrong
extra = []
if os.name != "nt":
    import PySide6
    plugins = os.path.join(os.path.dirname(PySide6.__file__), "Qt", "plugins")
    for sub in ("platforms", "wayland-shell-integration", "wayland-decoration-client",
                "wayland-graphics-integration-client", "platforminputcontexts",
                "xcbglintegrations", "egldeviceintegrations", "platformthemes",
                "iconengines", "imageformats"):
        folder = os.path.join(plugins, sub)
        if os.path.isdir(folder):
            extra += [(os.path.join(folder, f), os.path.join("PySide6", "Qt", "plugins", sub))
                      for f in os.listdir(folder) if f.endswith(".so")]

# fedtail/_vendor as files too: its packages are imported by their own names from there
# (fedtail/_vendor/__init__.py), not as fedtail's submodules
a = Analysis([{main!r}], pathex=[{root!r}],
             datas=[({data!r}, "fedtail/data"), ({vendor!r}, "fedtail/_vendor")],
             binaries=extra, hiddenimports=collect_submodules("fedtail"))
if os.name != "nt":
    a.binaries = [b for b in a.binaries
                  if not os.path.basename(b[0]).startswith({system!r})]
pyz = PYZ(a.pure)
exe = EXE(pyz, a.scripts, a.binaries, a.datas, [], name="fedtail", console={console!r},
          icon={icon}, upx=False, runtime_tmpdir=None)
"""


def main():
    sys.path.insert(0, str(ROOT))
    from fedtail import version
    info = version.info()
    build = ROOT / "fedtail" / "_build.py"
    build.write_text(f"BUILD = {info['version']!r}\nCOMMIT = {info['commit']!r}\n"
                     f"DATE = {info['date']!r}\n", "utf-8")
    print("building fedtail", info["version"])
    icon = None
    if WINDOWS:
        icon = ROOT / "build" / "fedtail.ico"
        icon.parent.mkdir(exist_ok=True)
        subprocess.run([sys.executable, str(ROOT / "packaging" / "make_icon.py"),
                        str(ROOT / "fedtail" / "data" / "icons" / "fedtail.png"), str(icon)],
                       check=True)
    spec = ROOT / "build" / "fedtail.spec"
    spec.parent.mkdir(exist_ok=True)
    spec.write_text(SPEC.format(main=str(ROOT / "packaging" / "fedtail_main.py"),
                                root=str(ROOT), data=str(ROOT / "fedtail" / "data"),
                                vendor=str(ROOT / "fedtail" / "_vendor"),
                                console=not WINDOWS, icon=repr(str(icon)) if icon else None,
                                system=SYSTEM_LIBS), "utf-8")
    try:
        subprocess.run([sys.executable, "-m", "PyInstaller", "--noconfirm",
                        "--distpath", str(ROOT / "dist"), "--workpath", str(ROOT / "build"),
                        str(spec)], check=True, cwd=ROOT)
    finally:
        build.unlink(missing_ok=True)
    out = ROOT / "dist" / ("fedtail.exe" if WINDOWS else "fedtail")
    print("built", out, out.stat().st_size // (1024 * 1024), "MB")


if __name__ == "__main__":
    main()
